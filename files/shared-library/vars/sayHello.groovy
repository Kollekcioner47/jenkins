/*
 * vars/sayHello.groovy — простейший шаг общей библиотеки (практика 13).
 *
 * Файл в каталоге vars/ превращается в шаг конвейера: имя шага — имя файла
 * без расширения, а его поведение — метод call(). Именно поэтому такой шаг
 * можно вызвать в Jenkinsfile как sayHello('аргумент').
 *
 * Значение по умолчанию у параметра не декоративно: шаг из общей библиотеки
 * вызывают десятки конвейеров, и добавление обязательного параметра
 * сломает их все разом. Поэтому новые параметры добавляют со значением
 * по умолчанию.
 */
def call(String name = 'DevOps') {
    echo "Привет, ${name}! Это шаг из общей библиотеки лаборатории."
    echo "Выполняется на агенте: ${env.NODE_NAME}, сборка ${env.BUILD_NUMBER}"
}
