#!/usr/bin/env bash
#
# Сквозная проверка выкаченного сайта.
#
# Запускается с контроллера Jenkins (или с любой машины в сети) и проверяет
# не файлы на диске, а то, что реально отдаёт веб-сервер. Разница
# принципиальная: файлы могут лежать на месте, а nginx — отдавать
# другой каталог, кэш — держать старую страницу, права — мешать чтению.
#
# Использование:
#     smoke_test.sh <url> [ожидаемый-текст] [ожидаемый-номер-сборки]
#
# Примеры:
#     smoke_test.sh http://10.0.2.13/
#     smoke_test.sh http://10.0.2.13/ "Hello from DevOps Engineer" 42
#
# Код возврата 0 — проверка пройдена, 1 — нет. Именно по коду возврата
# конвейер решает, выкатывать ли дальше или откатываться.

set -euo pipefail

URL="${1:-}"
EXPECTED_TEXT="${2:-Hello from DevOps Engineer}"
EXPECTED_BUILD="${3:-}"

[ -n "${URL}" ] || { echo "укажите URL: $0 http://адрес/ [текст] [номер сборки]" >&2; exit 2; }

BODY_FILE="$(mktemp)"
trap 'rm -f "${BODY_FILE}"' EXIT

fail() { echo "ПРОВЕРКА НЕ ПРОЙДЕНА: $*" >&2; exit 1; }

# -f: считать ошибкой код ответа 4xx/5xx; -S: показать причину;
# --max-time: не висеть вечно, если сервер не отвечает.
HTTP_CODE="$(curl -sS -o "${BODY_FILE}" -w '%{http_code}' --max-time 10 "${URL}")" \
    || fail "не удалось подключиться к ${URL}"

[ "${HTTP_CODE}" = "200" ] || fail "ожидался код 200, получен ${HTTP_CODE}"

grep -q "${EXPECTED_TEXT}" "${BODY_FILE}" \
    || fail "в ответе нет ожидаемого текста «${EXPECTED_TEXT}»"

# Оставшийся маркер означает, что шаг подстановки версии не выполнился.
# Такое надо ловить до того, как это увидит пользователь.
if grep -q '__BUILD_NUMBER__' "${BODY_FILE}"; then
    fail "в странице остался маркер __BUILD_NUMBER__"
fi

if [ -n "${EXPECTED_BUILD}" ]; then
    grep -q ">${EXPECTED_BUILD}<" "${BODY_FILE}" \
        || fail "страница отдаёт не сборку ${EXPECTED_BUILD}: подстановка или выкат не сработали"
fi

echo "OK: ${URL} отвечает 200, текст на месте, сборка ${EXPECTED_BUILD:-не проверялась}"
